import { createHash } from "node:crypto";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative, resolve, sep } from "node:path";
import type { Plugin } from "vite";

/** Prefix of every cache the service worker keeps; one per version of the game. */
export const CACHE_PREFIX = "vigilans-nexum-";

/** The service worker's own file, written to the root of the build. */
export const SERVICE_WORKER = "sw.js";

/** Every file under `dir`, as a site path ("/assets/index-ab12.js"), sorted. */
export function siteFiles(dir: string): string[] {
	const walk = (current: string): string[] =>
		readdirSync(current, { withFileTypes: true }).flatMap((entry) => {
			const path = join(current, entry.name);
			return entry.isDirectory() ? walk(path) : [path];
		});

	return walk(dir)
		.map((path) => "/" + relative(dir, path).split(sep).join("/"))
		.filter((path) => path !== `/${SERVICE_WORKER}` && !path.endsWith(".map"))
		.sort();
}

/** A short hash of every file's path and content: it changes exactly when the build does. */
export function buildVersion(dir: string, files: string[]): string {
	const hash = createHash("sha256");

	for (const file of files) {
		hash.update(file);
		hash.update(readFileSync(join(dir, file)));
	}

	return hash.digest("hex").slice(0, 12);
}

/**
 * The service worker for one build. On install it stores every file of the
 * build under a cache named for that build; every request for one of them is
 * then answered from the cache, so the game starts and plays with no network
 * at all. A page load answers with the stored index.html.
 *
 * A new build is a new worker with a new cache. It waits, as service workers
 * do, until no tab of the old version is open - the running game never has
 * its files swapped underneath it - and on taking over deletes the old cache.
 * So an update reaches the player on the next start after it was published.
 */
export function serviceWorkerSource(version: string, files: string[]): string {
	return `// Generated by tools/offline.ts - do not edit.
const CACHE = ${JSON.stringify(CACHE_PREFIX + version)};
const FILES = ${JSON.stringify(["/", ...files])};

self.addEventListener("install", (event) => {
	event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(FILES)));
});

self.addEventListener("activate", (event) => {
	event.waitUntil(
		caches
			.keys()
			.then((keys) => Promise.all(keys.filter((key) => key.startsWith(${JSON.stringify(CACHE_PREFIX)}) && key !== CACHE).map((key) => caches.delete(key))))
			.then(() => self.clients.claim())
	);
});

self.addEventListener("fetch", (event) => {
	const request = event.request;

	if (request.method !== "GET" || new URL(request.url).origin !== self.location.origin) {
		return;
	}

	event.respondWith(
		caches.open(CACHE).then(async (cache) => {
			// ignoreVary: the bundle is loaded crossorigin, and a server answering with
			// "Vary: Origin" would otherwise keep it from matching what install stored.
			const options = { ignoreSearch: true, ignoreVary: true };
			const stored = (await cache.match(request, options)) ?? (request.mode === "navigate" ? await cache.match("/index.html", options) : undefined);
			return stored ?? fetch(request);
		})
	);
});
`;
}

/**
 * Vite plugin: after a build, writes `sw.js` next to it, listing every file the
 * build produced - the bundle and everything copied from the public directory
 * (maps, unit sheets, tilesets, fonts) - so the whole game can be played
 * offline once it has been opened online. Builds only; the dev server has none.
 */
export function offline(): Plugin {
	let outDir = "dist";

	return {
		name: "vigilans-offline",
		apply: "build",
		configResolved(config) {
			// outDir is given relative to root (src); resolve leaves an absolute one alone.
			outDir = resolve(config.root, config.build.outDir);
		},
		closeBundle() {
			const files = siteFiles(outDir);
			const version = buildVersion(outDir, files);

			writeFileSync(join(outDir, SERVICE_WORKER), serviceWorkerSource(version, files));
			this.info?.(`${SERVICE_WORKER}: ${files.length} files cached as ${CACHE_PREFIX}${version}`);
		}
	};
}
